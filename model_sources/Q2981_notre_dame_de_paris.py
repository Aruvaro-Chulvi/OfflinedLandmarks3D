def stone(k=1.0):
    return tuple(np.clip(STONE * k * (1 + rng.normal(0, 0.012)), 0, 1))


def B(x0, x1, y0, y1, z0, z1, c):
    return box(x1 - x0, y1 - y0, z1 - z0, c).T((x0 + x1) / 2, y0, (z0 + z1) / 2)


def sphere(r, c, seg=8, rings=5):
    prof = [(r * math.sin(t), -r * math.cos(t)) for t in np.linspace(0, math.pi, rings + 1)]
    return lathe(prof, c, seg)


def obox(p, q, y0, y1, w, c):
    """A box along the segment p→q (plan), w thick, from y0 to y1."""
    (x0, z0), (x1, z1) = p, q
    L = math.hypot(x1 - x0, z1 - z0)
    a = math.atan2(-(z1 - z0), x1 - x0)
    return box(L, y1 - y0, w, c).R(0, a, 0).T((x0 + x1) / 2, y0, (z0 + z1) / 2)


def ccw(ring):
    return list(ring) if ring_area(ring) > 0 else list(ring)[::-1]


def centroid(ring):
    P = np.asarray(ring, float)
    return float(P[:, 0].mean()), float(P[:, 1].mean())


def fr(p, n):
    """A wall frame at plan point p with outward normal n: (origin, tangent, normal); u runs along the tangent."""
    nn = np.array([n[0], 0.0, n[1]], float)
    nn /= np.linalg.norm(nn)
    return np.array([p[0], 0.0, p[1]], float), np.array([nn[2], 0.0, -nn[0]]), nn


def plane_poly(pts_uv, origin, t, n, c):
    """A flat polygon given in wall coordinates (u along t, v = height) facing n."""
    pts, tris = triangulate(pts_uv)
    o = np.asarray(origin, float)
    V = np.array([o + u * np.asarray(t) + np.array([0, v, 0]) for u, v in pts])
    m = Mesh(V, tris, c)
    if np.dot(np.cross(t, [0.0, 1.0, 0.0]), n) < 0:   # keep the front face towards n
        m.f = m.f[:, ::-1]
    return m


def poly_on(F, pts, eps, c):
    o, t, n = F
    return plane_poly(pts, o + n * eps, t, n, c)


def rect_on(F, s, y0, w, h, eps, c):
    return poly_on(F, [(s - w / 2, y0), (s + w / 2, y0), (s + w / 2, y0 + h), (s - w / 2, y0 + h)], eps, c)


def lancet_pts(s, y0, w, h, sharp=0.9, seg=5):
    """A pointed (Gothic) arch, two arcs of radius sharp·w meeting at the apex, total height h."""
    R = max(sharp, 0.5) * w
    rise = math.sqrt(max(R * R - (R - w / 2) ** 2, 0.0))
    ys = y0 + h - rise
    aa = math.acos(max(-1.0, min(1.0, (w / 2 - R) / R)))
    pts = [(s - w / 2, y0), (s + w / 2, y0)]
    cr = s + w / 2 - R
    pts += [(cr + R * math.cos(a), ys + R * math.sin(a)) for a in np.linspace(0, math.pi - aa, seg + 1)]
    cl = s - w / 2 + R
    pts += [(cl + R * math.cos(a), ys + R * math.sin(a)) for a in np.linspace(aa, math.pi, seg + 1)[1:]]
    out = []
    for p in pts:
        if not out or math.dist(out[-1], p) > 1e-4:
            out.append(p)
    if math.dist(out[0], out[-1]) < 1e-4:
        out.pop()
    return out


def lancet_on(F, s, y0, w, h, eps, c, sharp=0.9):
    return poly_on(F, lancet_pts(s, y0, w, h, sharp), eps, c)


def disc_on(F, s, y, r, eps, c, seg=20):
    return poly_on(F, [(s + r * math.cos(a), y + r * math.sin(a)) for a in np.linspace(0, 2 * math.pi, seg, endpoint=False)], eps, c)


def ring_on(F, s, y, r0, r1, eps, c, seg=24):
    o, t, n = F
    a = np.linspace(0, 2 * math.pi, seg, endpoint=False)
    V, f = [], []
    for r in (r0, r1):
        for ang in a:
            V.append(o + n * eps + t * (s + r * math.cos(ang)) + np.array([0, y + r * math.sin(ang), 0]))
    for i in range(seg):
        j = (i + 1) % seg
        f += [(i, seg + i, seg + j), (i, seg + j, j)]
    m = Mesh(V, f, c)
    tri = m.v[m.f[0]]
    if np.dot(np.cross(tri[1] - tri[0], tri[2] - tri[0]), n) < 0:
        m.f = m.f[:, ::-1]
    return m


def spoke_on(F, s, y, r0, r1, ang, w, eps, c):
    ca, sa = math.cos(ang), math.sin(ang)
    px, py = -sa * w / 2, ca * w / 2
    pts = [(s + ca * r0 + px, y + sa * r0 + py), (s + ca * r0 - px, y + sa * r0 - py),
           (s + ca * r1 - px, y + sa * r1 - py), (s + ca * r1 + px, y + sa * r1 + py)]
    return poly_on(F, pts, eps, c)


def rose(F, s, y, r, eps, spokes=24):
    """A rose window: glass, stone rim, inner ring, radiating mullions and a ring of little roundels."""
    ms = [disc_on(F, s, y, r, eps, ROSE_G, seg=28), ring_on(F, s, y, r, r * 1.12, eps + 0.03, STONE_L, seg=28),
          ring_on(F, s, y, r * 0.22, r * 0.3, eps + 0.04, STONE_L, seg=16),
          ring_on(F, s, y, r * 0.62, r * 0.68, eps + 0.04, STONE_L, seg=24)]
    for k in range(spokes):
        a = 2 * math.pi * k / spokes
        ms.append(spoke_on(F, s, y, r * 0.3, r, a, max(0.1, r * 0.035), eps + 0.05, STONE_L))
    for k in range(spokes // 2):
        a = 2 * math.pi * (k + 0.5) / (spokes // 2)
        ms.append(ring_on(F, s + r * 0.83 * math.cos(a), y + r * 0.83 * math.sin(a), r * 0.07, r * 0.11, eps + 0.05, STONE_L, seg=8))
    return merge(ms)


def slab(F, pts_uv, thick, c, off=0.0):
    """A solid plate: a polygon drawn in a wall plane (u, height), thick along the frame's normal."""
    o, t, n = F
    pts, tris = triangulate(pts_uv)
    k = len(pts)

    def P(u, v, w):
        return o + t * u + np.array([0, v, 0]) + n * w

    V = [P(u, v, off + thick / 2) for u, v in pts] + [P(u, v, off - thick / 2) for u, v in pts]
    f = [tuple(tr) for tr in tris] + [(a + k, c_ + k, b + k) for a, b, c_ in tris]
    m = Mesh(V, f, c)
    if np.dot(np.cross(m.v[f[0][1]] - m.v[f[0][0]], m.v[f[0][2]] - m.v[f[0][0]]), n) < 0:
        m.f = m.f[:, ::-1]
    # rim
    R = ccw(pts.tolist())
    rim = []
    for i in range(len(R)):
        (u0, v0), (u1, v1) = R[i], R[(i + 1) % len(R)]
        a, b = P(u0, v0, off + thick / 2), P(u1, v1, off + thick / 2)
        cc, d = P(u1, v1, off - thick / 2), P(u0, v0, off - thick / 2)
        rim.append(Mesh([a, b, cc, d], [(0, 2, 1), (0, 3, 2)], c))
    return merge([m] + rim)


def gable_z(z0, z1, hw, y0, y1, c, xc=0.0):
    """Two roof slopes along z (ridge at x = xc)."""
    V = [(xc - hw, y0, z0), (xc - hw, y0, z1), (xc, y1, z1), (xc, y1, z0),
         (xc + hw, y0, z0), (xc + hw, y0, z1), (xc, y1, z1), (xc, y1, z0)]
    return Mesh(V, [(0, 2, 1), (0, 3, 2), (4, 5, 6), (4, 6, 7)], c)


def gable_x(x0, x1, hw, y0, y1, c, zc=0.0):
    V = [(x0, y0, zc - hw), (x1, y0, zc - hw), (x1, y1, zc), (x0, y1, zc),
         (x0, y0, zc + hw), (x1, y0, zc + hw), (x1, y1, zc), (x0, y1, zc)]
    return Mesh(V, [(0, 2, 1), (0, 3, 2), (4, 5, 6), (4, 6, 7)], c)


def half_cone(cx, cz, r, y0, y1, a0, a1, c, seg=14):
    a = np.linspace(a0, a1, seg + 1)
    V = [(cx + r * math.cos(t), y0, cz + r * math.sin(t)) for t in a] + [(cx, y1, cz)]
    k = len(a)
    return Mesh(V, [(i, k, i + 1) for i in range(seg)], c)


def hip(x0, x1, z0, z1, y0, y1, c):
    """Hipped roof over a rectangle."""
    dx, dz = x1 - x0, z1 - z0
    if dx >= dz:
        h = dz / 2
        a, b = (x0 + h, y1, (z0 + z1) / 2), (x1 - h, y1, (z0 + z1) / 2)
        V = [(x0, y0, z0), (x1, y0, z0), (x1, y0, z1), (x0, y0, z1), a, b]
        f = [(0, 4, 5), (0, 5, 1), (1, 5, 2), (2, 5, 4), (2, 4, 3), (3, 4, 0)]
    else:
        h = dx / 2
        a, b = ((x0 + x1) / 2, y1, z0 + h), ((x0 + x1) / 2, y1, z1 - h)
        V = [(x0, y0, z0), (x1, y0, z0), (x1, y0, z1), (x0, y0, z1), a, b]
        f = [(0, 4, 1), (1, 4, 5), (1, 5, 2), (2, 5, 3), (3, 5, 4), (3, 4, 0)]
    return Mesh(V, f, c)


def pyramid(ring, y0, y1, c):
    cx, cz = centroid(ring)
    R = ccw(ring)
    V = [(x, y0, z) for x, z in R] + [(cx, y1, cz)]
    k = len(R)
    return Mesh(V, [(i, k, (i + 1) % k) for i in range(k)], c)


def lean_roof(ring_in, ring_out, y_in, y_out, inset=0.25, step=1.2, seg=28):
    """Lean-to roofs round the core of the church: from the wall of ring_in (at y_in) down to the top of the wall of
    ring_out (at y_out), along both straight sides of the nave and the choir and round the chevet."""
    def reach(ring, p, d):
        h = ray_hit(ring, p, d)
        return math.inf if h is None else float(np.linalg.norm(h[0] - np.asarray(p)))

    def r_in(p, d, perp):                       # the wall of the core, not the transept arm next to it
        return min(reach(ring_in, p + perp * k, d) for k in (-1.5, 0.0, 1.5))

    def r_out(p, d, perp):
        return min(reach(ring_out, p + perp * k, d) for k in (-0.8, 0.0, 0.8)) - inset

    ms = []
    for z0, z1 in ((9.7, 52.8), (ZA, -9.8)):
        n = max(2, int(abs(z1 - z0) / step))
        zs = np.linspace(z0, z1, n + 1)
        for sign in (-1, 1):
            V = []
            for z in zs:
                p, d, perp = np.array([0.0, z]), np.array([sign, 0.0]), np.array([0.0, 1.0])
                V += [(sign * r_in(p, d, perp), y_in, z), (sign * r_out(p, d, perp), y_out, z)]
            f = []
            for i in range(n):
                a = 2 * i
                f += [(a, a + 2, a + 3), (a, a + 3, a + 1)]
            ms.append(Mesh(V, f, LEAD))
    V = []
    for a in np.linspace(math.pi, 2 * math.pi, seg + 1):
        d = np.array([math.cos(a), math.sin(a)])
        p = np.array([0.0, ZA])
        ri, ro = reach(ring_in, p, d), min(reach(ring_out, p, np.array([math.cos(a + k), math.sin(a + k)])) for k in (-0.03, 0.0, 0.03)) - inset
        V += [(d[0] * ri, y_in, ZA + d[1] * ri), (d[0] * ro, y_out, ZA + d[1] * ro)]
    f = []
    for i in range(seg):
        a = 2 * i
        f += [(a, a + 2, a + 3), (a, a + 3, a + 1)]
    ms.append(Mesh(V, f, LEAD))
    return merge(ms)


def parapet(ring, y, h, w, c, closed=True):
    """A balustrade wall along every edge of a ring, set inside by w/2."""
    R = ccw(ring)
    ms = []
    n = len(R) if closed else len(R) - 1
    for i in range(n):
        p, q = np.array(R[i]), np.array(R[(i + 1) % len(R)])
        L = np.linalg.norm(q - p)
        if L < 0.3:
            continue
        e = (q - p) / L
        nrm = np.array([e[1], -e[0]])
        ms.append(obox(p - nrm * w / 2, q - nrm * w / 2, y, y + h, w, c))
    return merge(ms)


def ray_hit(ring, p, d):
    """Farthest crossing of the ray p + t·d with a ring: (point, outward normal)."""
    R = ccw(ring)
    best = None
    for i in range(len(R)):
        a, b = np.array(R[i]), np.array(R[(i + 1) % len(R)])
        e = b - a
        M = np.array([[d[0], -e[0]], [d[1], -e[1]]])
        if abs(np.linalg.det(M)) < 1e-9:
            continue
        t, s = np.linalg.solve(M, a - np.asarray(p))
        if t > 0 and -1e-6 <= s <= 1 + 1e-6 and (best is None or t > best[0]):
            L = np.linalg.norm(e)
            best = (t, np.asarray(p) + t * np.asarray(d), np.array([e[1], -e[0]]) / L)
    return None if best is None else (best[1], best[2])


def strip_axis(P):
    """Centre line of a long thin OSM strip (a flying buttress): its two ends."""
    A = np.asarray(P, float)
    c = A.mean(0)
    _, _, vt = np.linalg.svd(A - c)
    d = vt[0]
    s = (A - c) @ d
    return c + d * s.min(), c + d * s.max()


def axd(p):
    """Distance from the axis of the church (and from the centre of the apse in the chevet)."""
    x, z = p
    return abs(x) if z > ZA else math.hypot(x, z - ZA)


def figure(x, y, z, h, c, r=None, face=0.0):
    """A standing statue: a tapering body on a little base, a head."""
    r = r or h * 0.15
    body = lathe([(r * 1.1, 0), (r * 1.1, h * 0.06), (r, h * 0.08), (r * 0.95, h * 0.45), (r * 0.8, h * 0.78),
                  (r * 0.55, h * 0.82), (0.0, h * 0.82)], c, 8)
    head = sphere(r * 0.62, c, 8, 5).T(0, h * 0.82 + r * 0.5, 0)
    return merge([body, head]).R(0, face, 0).T(x, y, z)


def chimera(x, y, z, face, c=CHIM):
    """A crouching chimera on a parapet."""
    b = box(0.55, 0.75, 0.8, c).T(0, 0, 0)
    head = sphere(0.26, c, 6, 4).T(0, 0.85, 0.32)
    wing = box(0.75, 0.35, 0.3, c).T(0, 0.45, -0.2)
    return merge([b, head, wing]).R(0, face, 0).T(x, y, z)



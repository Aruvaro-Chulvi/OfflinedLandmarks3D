def ccw(P):
    P = [tuple(p) for p in P]
    out = []
    for p in P:
        if not out or math.dist(out[-1], p) > 1e-3:
            out.append(p)
    if len(out) > 1 and math.dist(out[0], out[-1]) <= 1e-3:
        out.pop()
    return out if ring_area(out) > 0 else out[::-1]


def in_poly(x, z, P):
    inside = False
    n = len(P)
    j = n - 1
    for i in range(n):
        xi, zi = P[i]; xj, zj = P[j]
        if (zi > z) != (zj > z) and x < (xj - xi) * (z - zi) / (zj - zi + 1e-12) + xi:
            inside = not inside
        j = i
    return inside


def min_rect(P):
    """Smallest rectangle: centre, unit vectors along its long side (eu) and across (ev), half sizes A >= B."""
    P = np.asarray(P, float)
    best = None
    for i in range(len(P)):
        e = P[(i + 1) % len(P)] - P[i]
        L = np.linalg.norm(e)
        if L < 1e-6:
            continue
        eu = e / L; ev = np.array([-eu[1], eu[0]])
        u, v = P @ eu, P @ ev
        a = (u.max() - u.min()) * (v.max() - v.min())
        if best is None or a < best[0]:
            best = (a, eu, ev, u.min(), u.max(), v.min(), v.max())
    _, eu, ev, u0, u1, v0, v1 = best
    c = eu * (u0 + u1) / 2 + ev * (v0 + v1) / 2
    A, Bh = (u1 - u0) / 2, (v1 - v0) / 2
    if Bh > A:
        eu, ev, A, Bh = ev, -eu, Bh, A
    return c, eu, ev, A, Bh


def bearing_xz(deg):
    """A compass bearing as a unit vector in model x/z (heading 97.1°)."""
    h = math.radians(97.1); b = math.radians(deg)
    e, n = math.sin(b), math.cos(b)
    return np.array([-e * math.cos(h) + n * math.sin(h), e * math.sin(h) + n * math.cos(h)])


def roof_planes(P, shape, H, orient):
    """The roof as the lower envelope of planes f(x, z) = a x + b z + c (height above the eaves)."""
    if H <= 0 or shape in (None, "flat"):
        return [(0.0, 0.0, 0.0)]
    c, eu, ev, A, Bh = min_rect(P)
    if orient == "across":
        eu, ev, A, Bh = ev, eu, Bh, A

    def plane(dirv, dist0, slope):              # height = slope * (dist0 - (p - c)·dirv)
        a, b = -slope * dirv[0], -slope * dirv[1]
        return (a, b, slope * (dist0 + dirv[0] * c[0] + dirv[1] * c[1]))
    Bh = max(Bh, 0.3); A = max(A, 0.3)
    if shape == "gabled":
        s = H / Bh
        return [plane(ev, Bh, s), plane(-ev, Bh, s)]
    if shape == "hipped":
        s = H / Bh
        return [plane(ev, Bh, s), plane(-ev, Bh, s), plane(eu, A, s), plane(-eu, A, s)]
    if shape == "mansard":
        s = 2.4 * H / Bh
        return [plane(ev, Bh, s), plane(-ev, Bh, s), plane(eu, A, s), plane(-eu, A, s), (0.0, 0.0, H)]
    if shape == "skillion":
        return None                             # handled by the caller (needs the direction)
    # pyramidal, dome, round, onion…: a pyramid on the rectangle
    return [plane(ev, Bh, H / Bh), plane(-ev, Bh, H / Bh), plane(eu, A, H / A), plane(-eu, A, H / A)]


def skillion_planes(P, H, deg):
    w = bearing_xz(deg)
    s = np.asarray(P) @ w
    s0, s1 = s.min(), s.max()
    k = H / max(s1 - s0, 0.3)
    return [(-k * w[0], -k * w[1], k * s1)]


def ev_plane(pl, x, z):
    return pl[0] * x + pl[1] * z + pl[2]


def clip(poly, a, b, c):
    """Keep the part of a convex polygon where a x + b z + c <= 0."""
    out = []
    n = len(poly)
    for i in range(n):
        p, q = poly[i], poly[(i + 1) % n]
        fp, fq = a * p[0] + b * p[1] + c, a * q[0] + b * q[1] + c
        if fp <= 0:
            out.append(p)
        if (fp < 0 < fq) or (fq < 0 < fp):
            t = fp / (fp - fq)
            out.append((p[0] + t * (q[0] - p[0]), p[1] + t * (q[1] - p[1])))
    return out


def solid(P, y0, ye, planes, wall_c, roof_c, bottom=False):
    """A prism from y0 to the eaves ye, covered by the lower envelope of the roof planes."""
    P = ccw(P)
    out = []
    pts, tris = triangulate(P)
    V, F = [], []
    for tri in tris:
        T = [tuple(pts[k]) for k in tri]
        for i, pl in enumerate(planes):
            poly = T
            for j, pj in enumerate(planes):
                if j != i and poly:
                    poly = clip(poly, pl[0] - pj[0], pl[1] - pj[1], pl[2] - pj[2] - 1e-9 * (j < i))
            if len(poly) < 3:
                continue
            o = len(V)
            V += [(x, ye + ev_plane(pl, x, z), z) for x, z in poly]
            F += [(o, o + k + 1, o + k) for k in range(1, len(poly) - 1)]     # facing up
    if V:
        out.append(Mesh(V, F, roof_c))
    # walls, split where the roof changes plane so the gables follow the roof
    lines = [(planes[i][0] - planes[j][0], planes[i][1] - planes[j][1], planes[i][2] - planes[j][2])
             for i in range(len(planes)) for j in range(i + 1, len(planes))]
    V, F = [], []
    for k in range(len(P)):
        p, q = P[k], P[(k + 1) % len(P)]
        ts = [0.0, 1.0]
        for a, b, c in lines:
            fp, fq = a * p[0] + b * p[1] + c, a * q[0] + b * q[1] + c
            if (fp < 0 < fq) or (fq < 0 < fp):
                ts.append(fp / (fp - fq))
        ts.sort()
        for t0, t1 in zip(ts[:-1], ts[1:]):
            if t1 - t0 < 1e-6:
                continue
            a0 = (p[0] + t0 * (q[0] - p[0]), p[1] + t0 * (q[1] - p[1]))
            a1 = (p[0] + t1 * (q[0] - p[0]), p[1] + t1 * (q[1] - p[1]))
            h0 = ye + min(ev_plane(pl, *a0) for pl in planes)
            h1 = ye + min(ev_plane(pl, *a1) for pl in planes)
            o = len(V)
            V += [(a0[0], y0, a0[1]), (a1[0], y0, a1[1]), (a1[0], h1, a1[1]), (a0[0], h0, a0[1])]
            F += [(o, o + 2, o + 1), (o, o + 3, o + 2)]
    out.append(Mesh(V, F, wall_c))
    if bottom:
        out.append(Mesh([(x, y0, z) for x, z in pts], tris, wall_c))
    return merge(out)



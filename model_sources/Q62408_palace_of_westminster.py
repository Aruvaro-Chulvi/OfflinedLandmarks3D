class Box:
    """A hand-made solid (tower) for the exposure test of the walls."""
    def __init__(self, P, y0, top):
        self.P, self.mh, self.eave, self.h = ccw(P), y0, top, top
        xs = [p[0] for p in self.P]; zs = [p[1] for p in self.P]
        self.bb = (min(xs), max(xs), min(zs), max(zs))

    def contains(self, x, z):
        b = self.bb
        return b[0] <= x <= b[1] and b[2] <= z <= b[3] and in_poly(x, z, self.P)


def sq(c, h):
    return [(c[0] - h, c[1] - h), (c[0] + h, c[1] - h), (c[0] + h, c[1] + h), (c[0] - h, c[1] + h)]


def octagon(c, r, rot=math.pi / 8):
    return [(c[0] + r * math.cos(rot + k * math.pi / 4), c[1] + r * math.sin(rot + k * math.pi / 4)) for k in range(8)]


SOLIDS = PARTS + [Box(sq(ET, 6.6), 0, 60), Box(sq(VT, 11.0), 0, 86), Box(octagon(CT, 7.3), 25, 47)]


def covered_top(x, z, me):
    """Height up to which the point (x, z) is hidden by another solid (0 when open ground)."""
    h = 0.0
    for s in SOLIDS:
        if s is me or s.mh > h + 0.5:
            continue
        if s.eave > h and s.contains(x, z):
            h = s.eave
    return h


def part_mesh(p):
    y0 = p.mh if p.mh > 0 else FOUND
    if p.rs == "skillion" and p.rh > 0:
        planes = skillion_planes(p.P, p.rh, p.rd)
    else:
        planes = roof_planes(p.P, p.rs, p.rh, p.ro)
    pitched = p.rh > 0
    wall_c = tint(STONE, 0.025)
    roof_c = tint(ROOF if (p.dark or pitched) else ROOF_L, 0.03)
    if p.src == "H" and pitched:
        roof_c = tint(ROOF_H, 0.01)
    if pitched and p.small:
        roof_c = tint(STONE_L, 0.02)
    return solid(p.P, y0, p.eave, planes, wall_c, roof_c, bottom=p.mh > 0)



def bay_strip(L, y_lo, y_hi, top_free, wide=False):
    """Local mesh (u 0..L along the wall, w outwards) of one exposed wall band: shafts, windows, courses, parapet."""
    out = []
    n = max(1, int(round(L / 3.9)))
    step = L / n
    storey = 4.7
    floors = int((y_hi - y_lo - 1.6) // storey)
    # shafts (buttresses) at the bay divisions, rising above the parapet as small pinnacles
    for i in range(n + 1):
        u = i * step
        if (i == 0 or i == n) and L < 3:
            continue
        u = min(max(u, 0.25), L - 0.25)
        out.append(slab(u - 0.25, u + 0.25, y_lo, y_hi + (0.9 if top_free else 0.0), -0.05, 0.32, STONE_L,
                        top=not top_free))
        if top_free:
            out.append(cyl(0.3, 0.0, 1.5, STONE_L, 4, caps=False).R(0, math.pi / 4, 0).T(u, y_hi + 0.9, 0.14))
    # windows: two lights with a mullion under a label, one row per storey
    for f in range(floors):
        y0 = y_lo + 1.2 + f * storey
        y1 = y0 + (2.9 if f < floors - 1 or floors == 1 else 2.5)
        if y1 > y_hi - 0.9:
            break
        for i in range(n):
            u = (i + 0.5) * step
            hw = min(0.85, step / 2 - 0.55)
            if hw < 0.3:
                continue
            if wide and f == floors - 1:
                out.append(flat(pointed(u, y0, y1 - hw * 1.7, hw), GLASS).T(0, 0, 0.06))
            else:
                out.append(flat([(u - hw, y0), (u + hw, y0), (u + hw, y1), (u - hw, y1)], GLASS).T(0, 0, 0.06))
            out.append(flat([(u - 0.07, y0), (u + 0.07, y0), (u + 0.07, y1), (u - 0.07, y1)], STONE_L).T(0, 0, 0.1))
            out.append(flat([(u - hw - 0.2, y1 + 0.1), (u + hw + 0.2, y1 + 0.1), (u + hw + 0.2, y1 + 0.32),
                             (u - hw - 0.2, y1 + 0.32)], STONE_L).T(0, 0, 0.12))                     # label
        # string course under the windows
        if f > 0 and L > 1.5:
            out.append(slab(0.0, L, y0 - 0.55, y0 - 0.3, -0.05, 0.14, STONE_L))
    # parapet / cornice at the top of the band
    if top_free:
        out.append(B(0.0, L, y_hi - 0.5, y_hi + 0.75, -0.6, 0.22, STONE_L))
    return out


def hall_strip(L, y_lo, y_hi):
    """Westminster Hall and its flanking ranges: heavy buttresses and one row of tall pointed windows."""
    out = []
    n = max(1, int(round(L / 5.6)))
    step = L / n
    for i in range(n + 1):
        u = min(max(i * step, 0.45), L - 0.45)
        out.append(slab(u - 0.45, u + 0.45, y_lo, y_hi - 0.3, -0.05, 0.8, STONE_L))
    band = y_hi - y_lo
    if band >= 6:
        y0 = y_lo + max(1.5, band - 8.5)
        for i in range(n):
            u = (i + 0.5) * step
            hw = min(1.1, step / 2 - 0.9)
            if hw < 0.4:
                continue
            out.append(flat(pointed(u, y0, y_hi - 1.6 - hw * 1.75, hw), GLASS).T(0, 0, 0.06))
            out.append(flat([(u - 0.07, y0), (u + 0.07, y0), (u + 0.07, y_hi - 1.7), (u - 0.07, y_hi - 1.7)],
                            STONE_L).T(0, 0, 0.1))
    out.append(B(0.0, L, y_hi - 0.5, y_hi + 0.6, -0.6, 0.25, STONE_L))
    return out


def exposed_bays(p, idx):
    if p.small or p.eave - max(p.mh, 0) < 3.5 or p.dark:
        return None
    P = p.P
    parts = []
    for k in range(len(P)):
        a, b = np.array(P[k]), np.array(P[(k + 1) % len(P)])
        L = float(np.linalg.norm(b - a))
        if L < 2.2:
            continue
        t = (b - a) / L
        n = np.array([t[1], -t[0]])                    # outward for a counter-clockwise ring
        # sample the neighbour height along the edge, then split the edge where it changes
        m = max(2, int(L / 3.0))
        us = np.linspace(0, L, m + 1)
        mids = (us[:-1] + us[1:]) / 2
        cov = [covered_top(*(a + t * u + n * 0.7), p) for u in mids]
        segs = []
        for u0, u1, c in zip(us[:-1], us[1:], cov):
            if segs and abs(segs[-1][2] - c) < 0.5:
                segs[-1][1] = u1
            else:
                segs.append([u0, u1, c])
        for u0, u1, c in segs:
            y_lo = max(c, p.mh, 0.0)
            if p.eave - y_lo < 3.5 or u1 - u0 < 2.0:
                continue
            if p.src == "H":
                band = hall_strip(u1 - u0, y_lo, p.eave)
            else:
                band = bay_strip(u1 - u0, y_lo, p.eave, top_free=p.rh < 6 or p.rs == "gabled", wide=p.eave > 20)
            m_ = merge(band).T(u0, 0, 0)
            parts.append(to_frame(m_, a, t, n))
    return merge(parts) if parts else None


def pinnacle(p):
    """A small turret of the plan: octagonal shaft, a band and a crocketed spirelet."""
    c = np.mean(np.array(p.P), axis=0)
    r = max(0.45, math.sqrt(p.area / 2.83) * 0.98)
    y0 = p.mh if p.mh > 0 else FOUND
    top = p.eave
    sp = max(p.rh, 3.2 * r)
    out = [cyl(r, r, top - y0, tint(STONE, 0.02), 8, caps=False).T(c[0], y0, c[1]),
           cyl(r * 1.15, r * 1.15, 0.5, STONE_L, 8).T(c[0], top - 0.5, c[1]),
           cyl(r * 1.02, 0.0, sp, STONE_L, 8, caps=False).T(c[0], top, c[1])]
    out.append(sphere(0.18, GOLD if p.h > 33 else STONE_L, 4, 3).T(c[0], top + sp + 0.1, c[1]))
    return merge(out)


def cresting(p):
    """Iron cresting on the ridge of a long gabled roof (the ridge of its smallest rectangle)."""
    if p.rs not in ("gabled", "mansard", "hipped") or p.dark:
        return None
    c, eu, ev, A, Bh = min_rect(p.P)
    if p.ro == "across":
        eu, ev, A, Bh = ev, eu, Bh, A
    if abs(ring_area(p.P)) < 0.8 * 4 * A * Bh or A < 4:
        return None
    if p.rs == "hipped":
        A = A - Bh
    L = 2 * A - 0.4
    if L < 2:
        return None
    y = p.h
    # a pierced iron band (one double-sided strip) with a fleur spike every 0.9 m
    V = [(-L / 2, y, 0.0), (L / 2, y, 0.0), (L / 2, y + 0.55, 0.0), (-L / 2, y + 0.55, 0.0)]
    F = [(0, 1, 2), (0, 2, 3)]
    n = max(2, int(L / 0.9))
    for i in range(n + 1):
        u = -L / 2 + i * L / n
        o = len(V)
        V += [(u - 0.12, y + 0.5, 0.0), (u + 0.12, y + 0.5, 0.0), (u, y + 1.0, 0.0)]
        F.append((o, o + 1, o + 2))
    out = [Mesh(V, F, IRON)]
    for u in (-L / 2, L / 2):
        out.append(cyl(0.08, 0.02, 1.4, GOLD, 4, caps=False).T(u, y, 0))
    m = merge(out)
    v = m.v.copy()
    m.v = np.stack([c[0] + v[:, 0] * eu[0] + v[:, 2] * ev[0], v[:, 1], c[1] + v[:, 0] * eu[1] + v[:, 2] * ev[1]], 1)
    if eu[0] * ev[1] - eu[1] * ev[0] > 0:
        m.f = m.f[:, ::-1]
    return m



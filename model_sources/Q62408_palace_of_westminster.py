            out.append(cyl(r * 0.95, 0.0, 98.5 - ttop - 1.6, STONE_L, 8).T(px, ttop + 0.8, pz))
            out.append(cyl(0.06, 0.06, 1.8, GOLD, 4).T(px, 97.6, pz))
            out.append(B(px - 0.02, px + 0.02, 98.6, 99.2, pz - 0.5, pz + 0.5, GOLD))           # vane
            for y0 in (20.0, 45.0, 66.0):                                                      # slit windows
                a = math.atan2(sz, sx)
                o = (px + r * math.cos(a), pz + r * math.sin(a))
                tt = (-math.sin(a), math.cos(a))

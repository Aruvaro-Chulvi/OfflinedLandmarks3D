def fnum(s, d=0.0):
    try:
        return float(str(s).replace("m", "").strip())
    except (TypeError, ValueError):
        return d


class Part:
    def __init__(self, d):
        self.id, self.src = d["id"], d["s"]
        self.P = ccw(d["r"])
        self.h = fnum(d.get("h"), 10.0)
        self.mh = fnum(d.get("mh"), 0.0)
        self.rs = d.get("rs")
        self.rh = fnum(d.get("rh"), 0.0)
        if self.rs in ("gabled", "hipped", "mansard", "skillion", "pyramidal", "dome", "round") and self.rh <= 0:
            self.rh = min(4.0, (self.h - self.mh) * 0.3)
        if self.rs in (None, "flat"):
            self.rh = 0.0
        self.ro, self.rd = d.get("ro"), fnum(d.get("rd"), 0.0)
        self.dark = d.get("bc") == "#666666"
        self.area = abs(ring_area(self.P))
        self.eave = self.h - self.rh
        xs = [p[0] for p in self.P]; zs = [p[1] for p in self.P]
        self.bb = (min(xs), max(xs), min(zs), max(zs))
        self.small = self.area < 12.0 and self.rs in ("pyramidal", "dome", "round", None, "flat") and self.h > 15

    def contains(self, x, z):
        b = self.bb
        return b[0] <= x <= b[1] and b[2] <= z <= b[3] and in_poly(x, z, self.P)



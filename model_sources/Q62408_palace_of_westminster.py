def prism(pts, w0, w1, c):
    """A convex profile pts [(u, y)] extruded from w0 to w1."""
    n = len(pts)
    if sum(pts[i][0] * pts[(i + 1) % n][1] - pts[(i + 1) % n][0] * pts[i][1] for i in range(n)) < 0:
        pts = pts[::-1]
    V = [(u, y, w0) for u, y in pts] + [(u, y, w1) for u, y in pts]
    F = [(n, n + i, n + i + 1) for i in range(1, n - 1)] + [(0, i + 1, i) for i in range(1, n - 1)]
    m = Mesh(V, F, c)
    sides = []
    for i in range(n):
        (u0, y0), (u1, y1) = pts[i], pts[(i + 1) % n]
        sides.append(Mesh([(u0, y0, w0), (u1, y1, w0), (u1, y1, w1), (u0, y0, w1)], [(0, 1, 2), (0, 2, 3)], c))
    return merge([m] + sides)


def pyramid_frustum(cx, cz, r0, r1, y0, y1, c):
    """Square frustum (or pyramid if r1 = 0), half sizes r0 at y0 and r1 at y1, with its sides facing out."""
    out = []
    corners = [(-1, -1), (1, -1), (1, 1), (-1, 1)]
    for i in range(4):
        a, b = corners[i], corners[(i + 1) % 4]
        V = [(cx + a[0] * r0, y0, cz + a[1] * r0), (cx + b[0] * r0, y0, cz + b[1] * r0),
             (cx + b[0] * r1, y1, cz + b[1] * r1), (cx + a[0] * r1, y1, cz + a[1] * r1)]
        m = Mesh(V, [(0, 2, 1), (0, 3, 2)], c)
        nrm = np.cross(m.v[2] - m.v[0], m.v[1] - m.v[0])
        out_dir = np.array([a[0] + b[0], 0, a[1] + b[1]])
        if np.dot(nrm, out_dir) < 0:
            m.f = m.f[:, ::-1]
        out.append(m)
    if r1 > 0:
        out.append(B(cx - r1, cx + r1, y1 - 0.01, y1, cz - r1, cz + r1, c))
    return merge(out)


# ── Victoria Tower ──────────────────────────────────────────────────────────
def victoria_tower():
    cx, cz = VT
    out = []
    W = 10.15                                                # body 20.3 m square (OSM)
    TOP = 84.0 * VK                                          # parapet top
    out.append(B(cx - W, cx + W, FOUND, TOP - 1.6, cz - W, cz + W, STONE))
    for y in (14.0, 17.0, 28.0, 40.0, 51.0, 63.0, 73.0):
        y *= VK
        out.append(B(cx - W - 0.3, cx + W + 0.3, y - 0.2, y + 0.45, cz - W - 0.3, cz + W + 0.3, STONE_L))
    # parapet with a pierced band and pinnacles
    out.append(B(cx - W, cx + W, TOP - 1.6, TOP, cz - W, cz + W, STONE_L))
    out.append(pyramid_frustum(cx, cz, W - 0.6, 3.0, TOP - 1.0, 88.5 * VK + 1.0, ROOF))
    # flagstaff (OSM: to 120 m) with the Union Flag
    out.append(cyl(0.22, 0.12, 120.0 - (88.5 * VK + 1.0), STONE_L, 8).T(cx, 88.5 * VK + 1.0, cz))
    out.append(sphere(0.3, GOLD, 8, 5).T(cx, 120.0, cz))
    out.append(union_flag(cx, 116.6, cz))

    def face(k):
        f = []
        for u in (-5.6, -1.9, 1.9, 5.6):                    # buttress ribs
            f.append(B(u - 0.3, u + 0.3, 18.0 if (k in (2, 3) and abs(u) < 3) else 0.0, TOP - 1.6, -0.05, 0.4, STONE_L))
        if k in (2, 3):                                       # Sovereign's Entrance (west and south faces)
            f.append(flat(pointed(0, 0.0, 9.0, 3.6, 6), DARK).T(0, 0, 0.06))
            f.append(prism(pointed(0, 0.0, 9.0, 4.4, 6), -0.05, 0.12, STONE_L))
            f.append(flat(pointed(0, 0.0, 9.0, 3.6, 6), DARK).T(0, 0, 0.14))
        else:
            for u in (-3.75, 0.0, 3.75):
                f.append(flat(pointed(u, 3.5, 9.5, 0.9), GLASS).T(0, 0, 0.06))
        for y0, y1 in ((18.2, 27.0), (29.6, 39.5), (42.0, 50.8), (53.6, 63.2)):    # panelled stages
            for u in (-7.6, -3.75, 0.0, 3.75, 7.6):
                hw = 0.7 if abs(u) > 7 else 1.0
                f.append(flat(pointed(u, y0, y1 - hw * 1.8, hw), GLASS).T(0, 0, 0.06))
                f.append(flat([(u - 0.07, y0), (u + 0.07, y0), (u + 0.07, y1 - 0.5), (u - 0.07, y1 - 0.5)], STONE_L).T(0, 0, 0.1))
                f.append(B(u - hw - 0.15, u + hw + 0.15, y0 - 0.35, y0 - 0.1, -0.05, 0.3, STONE_L))
        for u in (-3.75, 0.0, 3.75):                          # the tall windows of the top stage
            f.append(flat(pointed(u, 66.0, 79.0, 1.35, 5), GLASS).T(0, 0, 0.06))
            f.append(flat([(u - 0.08, 66.0), (u + 0.08, 66.0), (u + 0.08, 80.5), (u - 0.08, 80.5)], STONE_L).T(0, 0, 0.1))
            f.append(B(u - 1.35, u + 1.35, 72.4, 72.6, -0.05, 0.12, STONE_L))
        for u in (-5.6, -1.9, 1.9, 5.6):                      # pinnacles on the parapet
            f.append(cyl(0.35, 0.35, 2.0, STONE_L, 8).T(u, TOP, 0.0))
            f.append(cyl(0.4, 0.0, 2.6, STONE_L, 8).T(u, TOP + 2.0, 0.0))
        if k in (2, 3):                                       # royal arms over the entrance
            f.append(B(-1.5, 1.5, 14.6, 17.0, -0.05, 0.25, GOLD))
        return f
    out += tower_faces(VT, W, face)
    # octagonal corner turrets
    for sx in (-1, 1):
        for sz in (-1, 1):
            px, pz = cx + sx * (W - 0.4), cz + sz * (W - 0.4)
            r = 2.5
            ttop = 89.0 * VK
            out.append(cyl(r, r, ttop - FOUND, tint(STONE, 0.01), 8).T(px, FOUND, pz))
            for y in (14.0, 28.0, 51.0, 73.0, 84.0):
                out.append(cyl(r + 0.25, r + 0.25, 0.6, STONE_L, 8).T(px, y * VK, pz))

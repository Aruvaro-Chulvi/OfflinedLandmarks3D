def sphere(r, c, seg=8, rings=5):
    prof = [(r * math.sin(t), -r * math.cos(t)) for t in np.linspace(0, math.pi, rings + 1)]
    return lathe(prof, c, seg)


def slab(u0, u1, y0, y1, w0, w1, c, top=True):
    """A box against a wall (local u, y, w): only its front, sides and top, as the back and bottom never show."""
    V = [(u0, y0, w1), (u1, y0, w1), (u1, y1, w1), (u0, y1, w1),          # front
         (u0, y0, w0), (u0, y0, w1), (u0, y1, w1), (u0, y1, w0),          # left
         (u1, y0, w1), (u1, y0, w0), (u1, y1, w0), (u1, y1, w1)]          # right
    if top:
        V += [(u0, y1, w1), (u1, y1, w1), (u1, y1, w0), (u0, y1, w0)]
    F = []
    for q in range(len(V) // 4):
        o = 4 * q
        F += [(o, o + 1, o + 2), (o, o + 2, o + 3)]
    return Mesh(V, F, c)


def flat(pts, c):
    """A flat convex polygon in local (u, y) at w = 0, facing +w (local z)."""
    n = len(pts)
    V = [(u, y, 0.0) for u, y in pts]
    F = [(0, i, i + 1) for i in range(1, n - 1)]
    m = Mesh(V, F, c)
    if sum(pts[i][0] * pts[(i + 1) % n][1] - pts[(i + 1) % n][0] * pts[i][1] for i in range(n)) < 0:
        m.f = m.f[:, ::-1]
    return m


def pointed(u, y0, ys, half, seg=4):
    """Outline of a pointed (equilateral) Gothic opening: sill y0, springing ys, half-width half."""
    r = 2 * half
    pts = [(u - half, y0), (u + half, y0)]
    a0 = math.acos(0.5)                                          # 60°
    for a in np.linspace(0, a0, seg + 1)[:-1]:                   # right arc, centre at the left springing
        pts.append((u - half + r * math.cos(a), ys + r * math.sin(a)))
    pts.append((u, ys + r * math.sin(a0)))
    for a in np.linspace(a0, 0, seg + 1)[1:]:
        pts.append((u + half - r * math.cos(a), ys + r * math.sin(a)))
    return pts


def to_frame(m, origin, t, n):
    """Map a mesh built in local (u along t, y up, w along n) to the model; t, n horizontal unit vectors."""
    v = m.v
    o = np.array([origin[0], 0.0, origin[1]])
    T = np.array([t[0], 0.0, t[1]]); N = np.array([n[0], 0.0, n[1]])
    m.v = o + v[:, :1] * T + v[:, 1:2] * np.array([0, 1.0, 0]) + v[:, 2:3] * N
    if t[0] * n[1] - t[1] * n[0] < 0:            # left-handed frame: keep the faces outwards
        m.f = m.f[:, ::-1]
    return m


def face_frame(cx, cz, d, k):
    """Frame of side k (0: +Z, 1: +X, 2: −Z, 3: −X) of a square tower centred at (cx, cz), plane at distance d."""
    n = [(0, 1), (1, 0), (0, -1), (-1, 0)][k]
    t = (n[1], -n[0])                             # u to the right when looking at that face
    return (cx + n[0] * d, cz + n[1] * d), t, n


